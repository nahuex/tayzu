/**
 * Integration test for task 4.5 of change `003-catalog-ui-core` (design D10 "The style
 * nonce", ADR-0026; Resolved decisions Q15, Q45 (4) and Q60).
 *
 * Task 4.5 (verbatim): "The style nonce (design D10, Q15): Tayzu's own `onRequest` hook
 * draws a fresh 128-bit nonce from `crypto.randomBytes(16)` (base64) per request, the
 * `style-src` directive function reads it, and the fallback substitutes it into the
 * `tayzu-style-nonce` meta of the in-memory `index.html`; helmet's `enableCSPNonces` is
 * not used. Verify: `csp-nonce.http.int.test.ts` covers the header and the meta holding
 * the same value, two responses holding different values, the value being 16 bytes in
 * base64, `script-src` holding no nonce, and no nonce placeholder left in the served
 * page."
 *
 * Spec `specs/catalog-ui-core/spec.md`, requirement "Every response carries a strict,
 * self-only Content Security Policy" (excerpt): "A runtime style element MAY be allowed
 * only through a nonce that is unique per HTML response and generated by a
 * cryptographically secure source."
 *
 * > #### Scenario: The app page carries the policy
 * >
 * > - **GIVEN** the API is started with a build directory
 * > - **WHEN** a browser requests `GET /`
 * > - **THEN** the response carries the exact policy and headers above, and its nonce
 * >   differs from that of a second request
 *
 * The "exact policy and headers" part is `headers.int.test.ts` (task 4.4); this file is
 * the nonce clause.
 *
 * Design D10 "The style nonce" (excerpt): "Each HTML response gets a fresh 128-bit nonce
 * from `crypto.randomBytes(16)` (base64), generated by Tayzu's own `onRequest` hook and
 * read by the `style-src` directive function (not helmet's `enableCSPNonces`, which emits
 * hex and adds the nonce to `script-src` too), placed in the CSP header and in `<meta
 * name="tayzu-style-nonce" content="<n>">` of that response's `index.html` [...].
 * Non-HTML responses carry a nonce nothing uses."
 *
 * D10 "One policy on every response (HTML, JSON, assets and 404s)", with
 * `style-src 'self' 'nonce-<n>'` and `script-src 'self'` ("no nonce and no hash").
 *
 * Q45 (4): "The `index.html` nonce placeholder is `__TAYZU_STYLE_NONCE__`, which task 4.5
 * substitutes." Q60: helmet and the `Permissions-Policy` hook are registered just before
 * `002`'s Q74 request-target hook, so the 404s Q74 answers carry D10's headers too.
 *
 * ## What is asserted
 *
 * 1. On an app page (`GET /` and an app path) the `style-src` nonce of the CSP header and
 *    the `content` of the `tayzu-style-nonce` meta hold the same value.
 * 2. Two responses hold different values (and a batch of responses never repeats one).
 * 3. The value is 16 bytes in standard base64: `^[A-Za-z0-9+/]{22}==$`, decoding to
 *    exactly 16 bytes (helmet's `enableCSPNonces` would emit 32 hex characters).
 * 4. `script-src` holds no nonce (it is exactly `'self'`).
 * 5. No `__TAYZU_STYLE_NONCE__` placeholder is left in the served page.
 * 6. The meta is the only place the nonce appears in the body: no inline `<style>`, no
 *    `nonce` attribute on any element.
 * 7. Non-HTML responses (a `/v1` JSON `401`, a hashed asset, a root build file, Fastify's
 *    404 and the Q74 404 of a `%` target) carry a fresh nonce in `style-src` too: D10
 *    says "Non-HTML responses carry a nonce nothing uses", and the hook runs per request
 *    (Q60 puts the header-writing hooks ahead of Q74).
 * 8. A `HEAD` of an app path carries the same policy, with a nonce of the same shape.
 *
 * ## Harness
 *
 * One app with `webDistDir` set to the committed fixture `__fixtures__/web-dist/` (read
 * only), driven through `app.inject` with a fresh `x-forwarded-for` per request (the
 * fallback bucket never interferes). The Q74 target goes over a raw TCP socket to the
 * listening app, because `app.inject` may normalize a request target (the precedent is
 * `request-target.int.test.ts` and `spa-fallback.http.int.test.ts`).
 *
 * ## Production symbols expected (the red phase)
 *
 * - `createApp` (`./server.js`) registers Tayzu's own `onRequest` hook, ahead of helmet's
 *   hooks, that stores `randomBytes(16).toString('base64')` for the request; the
 *   `style-src` entry of `CSP_DIRECTIVES` gains a directive function returning
 *   `'nonce-<n>'` for that request; `enableCSPNonces` stays off.
 * - `registerSpaFallback` (`./spa-fallback.js`) answers the in-memory `index.html` with
 *   `__TAYZU_STYLE_NONCE__` replaced by that request's nonce.
 *
 * ## Why this fails right now
 *
 * `style-src` is `'self'` only and the fallback serves the placeholder verbatim: every
 * nonce assertion fails on the missing `'nonce-…'` source or on the placeholder. The
 * `script-src` checks already pass: they are guards the nonce must keep green.
 *
 * ## Extended by task 8.2 of `048-production-hardening` (design D9, Resolved decision Q10)
 *
 * Task 8.2: "The policy names the same-origin endpoint (design D9). Verify:
 * `apps/api/src/headers.int.test.ts` and `csp-nonce.http.int.test.ts` (extended) cover
 * "The app page carries the policy", "API responses carry the policy too" and "The policy
 * reports violations to the app's own origin" with the new exact policy and the
 * `Reporting-Endpoints` header on HTML, JSON, asset and `404` responses."
 *
 * Design D9 "Policy": "`CSP_DIRECTIVES` gains `'report-uri': ['/v1/csp-reports']` and
 * `'report-to': ['csp-endpoint']`, and the `Permissions-Policy` hook also sets
 * `Reporting-Endpoints: csp-endpoint="/v1/csp-reports"` on every response."
 *
 * `EXPECTED_POLICY` below is the exact policy: D10's directive list, with the response's
 * nonce in `style-src`, plus D9's two report directives. Every response of this app (the
 * app pages, a `HEAD`, the `/v1` JSON `401`, an asset, a root build file, the `404`s and
 * the Q74 `404`) must carry exactly that policy, its own nonce aside, and
 * `Reporting-Endpoints: csp-endpoint="/v1/csp-reports"`.
 *
 * Why task 8.2 fails right now: the served policy has no `report-uri` or `report-to` and
 * no `Reporting-Endpoints` header is set, so every exact-policy and `Reporting-Endpoints`
 * assertion fails. The nonce assertions of task 4.5 already pass and stay green.
 */
import { randomInt } from 'node:crypto';
import { connect, type AddressInfo } from 'node:net';
import { fileURLToPath } from 'node:url';

import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { TEST_SECRET } from '../../../packages/auth/src/__fixtures__/test-secret.js';
import { harnessPools } from './__fixtures__/pools.js';
import { createApp, type App } from './server.js';

const FIXTURE_WEB_DIST = fileURLToPath(new URL('./__fixtures__/web-dist/', import.meta.url));
const ORIGIN = 'https://app.tayzu.test';
const NONCE_PLACEHOLDER = '__TAYZU_STYLE_NONCE__';
const INDEX_MARKER = 'web-dist-index-html';
const HTML = /^text\/html; charset=utf-8$/i;

/** Task 4.5: 16 bytes of `crypto.randomBytes`, standard base64 (with its padding). */
const NONCE_VALUE = /^[A-Za-z0-9+/]{22}==$/;
const NONCE_BYTES = 16;
/** Any CSP nonce source, whatever its encoding. */
const ANY_NONCE_SOURCE = /^'nonce-(.*)'$/;
/** The style-nonce meta of the fixture `index.html`, capturing its `content`. */
const STYLE_NONCE_META = /<meta name="tayzu-style-nonce" content="([^"]*)"\s*\/?>/g;

const APP_PAGES: readonly string[] = ['/', '/catalog/service/payments'];

/** Stands for the response's own style nonce in `EXPECTED_POLICY`. */
const NONCE_SLOT = '<n>';
/**
 * The exact policy of `003` D10 plus `048` D9 (task 8.2): every directive with its exact
 * source list, `<n>` being the response's own nonce.
 */
const EXPECTED_POLICY =
  "default-src 'self'; script-src 'self'; style-src 'self' 'nonce-<n>'; " +
  "img-src 'self'; font-src 'self'; connect-src 'self'; media-src 'none'; " +
  "object-src 'none'; frame-src 'none'; worker-src 'none'; manifest-src 'self'; " +
  "base-uri 'none'; form-action 'self'; frame-ancestors 'none'; " +
  'report-uri /v1/csp-reports; report-to csp-endpoint';
/** 048 D9: the exact `Reporting-Endpoints` value on every response. */
const EXPECTED_REPORTING_ENDPOINTS = 'csp-endpoint="/v1/csp-reports"';

function randomIp(): string {
  const octet = (): string => randomInt(1, 255).toString(10);
  return `10.${octet()}.${octet()}.${octet()}`;
}

/** Reads a single-valued header as a string, failing the test on anything else. */
function singleHeader(value: string | string[] | number | undefined, name: string): string {
  if (typeof value !== 'string') {
    throw new Error(`expected exactly one ${name} header, got ${JSON.stringify(value)}`);
  }
  return value;
}

/** Directive name (lower case) to its source list, in header order. */
function parseCsp(header: string): ReadonlyMap<string, readonly string[]> {
  const directives = new Map<string, readonly string[]>();
  for (const part of header.split(';')) {
    const [rawName, ...sources] = part
      .trim()
      .split(/\s+/)
      .filter((token) => token.length > 0);
    if (rawName !== undefined && !directives.has(rawName.toLowerCase())) {
      directives.set(rawName.toLowerCase(), sources);
    }
  }
  return directives;
}

/** The CSP with every nonce source removed, so two responses can be compared. */
function cspWithoutNonces(header: string): Record<string, readonly string[]> {
  const result: Record<string, readonly string[]> = {};
  for (const [name, sources] of parseCsp(header)) {
    result[name] = sources.filter((source) => !ANY_NONCE_SOURCE.test(source));
  }
  return result;
}

/**
 * The one style nonce of a CSP header: `style-src` must be exactly `'self'` plus one
 * `'nonce-<n>'` source, and `<n>` is returned.
 */
function styleNonce(header: string, label: string): string {
  const styleSrc = parseCsp(header).get('style-src');
  expect(styleSrc, label).toBeDefined();
  const sources = styleSrc ?? [];
  expect(sources[0], label).toBe("'self'");
  const nonceSources = sources.filter((source) => ANY_NONCE_SOURCE.test(source));
  expect(nonceSources, label).toHaveLength(1);
  expect(sources, label).toHaveLength(2);
  const value = ANY_NONCE_SOURCE.exec(nonceSources[0] ?? '')?.[1];
  if (value === undefined) {
    throw new Error(`${label}: no style-src nonce`);
  }
  return value;
}

/**
 * Asserts that a served policy is exactly `EXPECTED_POLICY` with its own nonce in the
 * `<n>` slot: the same directives, each with the same source list, none repeated.
 */
function expectExactPolicy(header: string, label: string): void {
  const nonce = styleNonce(header, label);
  const names = header
    .split(';')
    .map((part) => part.trim().split(/\s+/)[0]?.toLowerCase() ?? '')
    .filter((name) => name.length > 0);
  expect(new Set(names).size, label).toBe(names.length);
  const expected = Object.fromEntries(parseCsp(EXPECTED_POLICY.replace(NONCE_SLOT, nonce)));
  expect(Object.fromEntries(parseCsp(header)), label).toEqual(expected);
}

/** Asserts the task 4.5 shape: 16 bytes in standard base64. */
function expectNonceShape(value: string, label: string): void {
  expect(value, label).toMatch(NONCE_VALUE);
  const decoded = Buffer.from(value, 'base64');
  expect(decoded.length, label).toBe(NONCE_BYTES);
  // A round trip proves the value is canonical standard base64, not base64url or hex.
  expect(decoded.toString('base64'), label).toBe(value);
}

/** Every `content` of a `tayzu-style-nonce` meta in the body. */
function metaNonces(body: string): string[] {
  return [...body.matchAll(STYLE_NONCE_META)].map((match) => match[1] ?? '');
}

function occurrences(haystack: string, needle: string): number {
  return haystack.split(needle).length - 1;
}

interface Observed {
  readonly statusCode: number;
  readonly body: string;
  readonly contentType: unknown;
  readonly csp: string;
  /** 048 D9: the raw `Reporting-Endpoints` header, absent today. */
  readonly reportingEndpoints: unknown;
}

let app: App;
let port: number;

async function call(method: 'GET' | 'HEAD', url: string): Promise<Observed> {
  const response = await app.app.inject({
    method,
    url,
    headers: { origin: ORIGIN, 'x-forwarded-for': randomIp() },
  });
  return {
    statusCode: response.statusCode,
    body: response.body,
    contentType: response.headers['content-type'],
    csp: singleHeader(response.headers['content-security-policy'], 'content-security-policy'),
    reportingEndpoints: response.headers['reporting-endpoints'],
  };
}

interface RawResponse {
  readonly statusCode: number;
  readonly headers: ReadonlyMap<string, string>;
}

/** Sends one HTTP/1.1 request line byte for byte and reads until the server closes. */
function rawGet(target: string): Promise<RawResponse> {
  return new Promise<RawResponse>((resolve, reject) => {
    const socket = connect({ host: '127.0.0.1', port });
    const chunks: Buffer[] = [];
    socket.on('connect', () => {
      socket.write(
        `GET ${target} HTTP/1.1\r\nhost: 127.0.0.1:${port.toString(10)}\r\n` +
          `x-forwarded-for: ${randomIp()}\r\nconnection: close\r\n\r\n`,
      );
    });
    socket.on('data', (chunk: Buffer) => {
      chunks.push(chunk);
    });
    socket.on('error', reject);
    socket.on('close', () => {
      const raw = Buffer.concat(chunks).toString('utf8');
      const [head = ''] = raw.split('\r\n\r\n', 1);
      const [statusLine = '', ...lines] = head.split('\r\n');
      const statusMatch = /^HTTP\/1\.1 (\d{3})/.exec(statusLine);
      if (statusMatch?.[1] === undefined) {
        reject(new Error('no HTTP status line in the response'));
        return;
      }
      const headers = new Map<string, string>();
      for (const line of lines) {
        const colon = line.indexOf(':');
        if (colon > 0) {
          headers.set(line.slice(0, colon).trim().toLowerCase(), line.slice(colon + 1).trim());
        }
      }
      resolve({ statusCode: Number(statusMatch[1]), headers });
    });
  });
}

beforeAll(async () => {
  app = await createApp({
    ...(await harnessPools()),
    authSecret: TEST_SECRET,
    cerbosAddress: 'localhost:3593',
    allowedOrigins: [ORIGIN],
    webDistDir: FIXTURE_WEB_DIST,
  });
  await app.app.listen({ host: '127.0.0.1', port: 0 });
  port = (app.app.server.address() as AddressInfo).port;
}, 60_000);

afterAll(async () => {
  await app.close();
}, 60_000);

describe('the per-response style nonce (003 task 4.5, design D10, Q15)', () => {
  describe('The app page carries the policy: the nonce clause', () => {
    for (const path of APP_PAGES) {
      it(`GET ${path}: the style-src nonce and the tayzu-style-nonce meta hold the same value`, async () => {
        const page = await call('GET', path);
        expect(page.statusCode, path).toBe(200);
        expect(page.contentType, path).toMatch(HTML);
        expect(page.body, path).toContain(INDEX_MARKER);

        const headerNonce = styleNonce(page.csp, path);
        const metas = metaNonces(page.body);
        expect(metas, path).toHaveLength(1);
        expect(metas[0], path).toBe(headerNonce);
      });

      it(`GET ${path}: the nonce is 16 bytes in standard base64`, async () => {
        const page = await call('GET', path);
        expectNonceShape(styleNonce(page.csp, path), path);
      });

      it(`GET ${path}: no ${NONCE_PLACEHOLDER} placeholder is left in the served page`, async () => {
        const page = await call('GET', path);
        expect(page.statusCode, path).toBe(200);
        expect(page.body, path).not.toContain(NONCE_PLACEHOLDER);
        expect(page.csp, path).not.toContain(NONCE_PLACEHOLDER);
      });

      it(`GET ${path}: the meta is the only place the nonce appears in the body`, async () => {
        const page = await call('GET', path);
        const nonce = styleNonce(page.csp, path);
        expect(occurrences(page.body, nonce), path).toBe(1);
        expect(metaNonces(page.body), path).toEqual([nonce]);
        // No inline style element and no nonce attribute on a script, a style or a link.
        expect(page.body, path).not.toMatch(/<style[\s>]/i);
        expect(page.body, path).not.toMatch(/\snonce\s*=/i);
      });

      // 048 task 8.2: "the exact policy and headers above", now with D9's report directives.
      it(`GET ${path}: carries the exact policy with the report directives and Reporting-Endpoints (048 D9)`, async () => {
        const page = await call('GET', path);
        expect(page.statusCode, path).toBe(200);
        expect(page.contentType, path).toMatch(HTML);
        expectExactPolicy(page.csp, path);
        expect(page.reportingEndpoints, path).toBe(EXPECTED_REPORTING_ENDPOINTS);
      });

      it(`GET ${path}: script-src holds no nonce ('self' only)`, async () => {
        const page = await call('GET', path);
        const scriptSrc = parseCsp(page.csp).get('script-src');
        expect(scriptSrc, path).toEqual(["'self'"]);
        expect(page.csp, path).toMatch(/style-src 'self' 'nonce-/);
      });
    }

    it('its nonce differs from that of a second request (GET / twice)', async () => {
      const first = await call('GET', '/');
      const second = await call('GET', '/');

      const firstNonce = styleNonce(first.csp, 'first GET /');
      const secondNonce = styleNonce(second.csp, 'second GET /');
      expect(secondNonce).not.toBe(firstNonce);
      expect(metaNonces(first.body)).toEqual([firstNonce]);
      expect(metaNonces(second.body)).toEqual([secondNonce]);
      // Everything but the nonce is the same policy.
      expect(cspWithoutNonces(second.csp)).toEqual(cspWithoutNonces(first.csp));
    });

    it('a batch of app-page responses never repeats a nonce', async () => {
      const responses = await Promise.all(
        Array.from({ length: 24 }, (_unused, index) =>
          call('GET', APP_PAGES[index % APP_PAGES.length] ?? '/'),
        ),
      );
      const nonces = responses.map((response, index) =>
        styleNonce(response.csp, `response ${index.toString(10)}`),
      );
      expect(new Set(nonces).size).toBe(nonces.length);
      for (const [index, response] of responses.entries()) {
        expect(metaNonces(response.body), `response ${index.toString(10)}`).toEqual([
          nonces[index],
        ]);
      }
    });
  });

  describe('non-HTML responses carry a nonce nothing uses (D10, the hook runs per request)', () => {
    const targets: readonly {
      readonly name: string;
      readonly url: string;
      readonly status: number;
    }[] = [
      { name: 'a /v1 JSON response (401)', url: '/v1/blueprints', status: 401 },
      { name: 'a hashed asset', url: '/assets/index-Fx7Wd1Aa.js', status: 200 },
      { name: 'a root build file', url: '/theme-init.js', status: 200 },
      { name: 'a missing asset (404)', url: '/assets/index-Nope0000.js', status: 404 },
      { name: 'an unlisted /api/auth path (404)', url: '/api/auth/unlisted', status: 404 },
    ];

    for (const target of targets) {
      it(`${target.name}: style-src holds a fresh 16-byte base64 nonce and script-src none`, async () => {
        const first = await call('GET', target.url);
        const second = await call('GET', target.url);
        expect(first.statusCode, target.url).toBe(target.status);
        expect(first.contentType, target.url).not.toMatch(/^text\/html/i);

        const firstNonce = styleNonce(first.csp, target.url);
        const secondNonce = styleNonce(second.csp, target.url);
        expectNonceShape(firstNonce, target.url);
        expectNonceShape(secondNonce, target.url);
        expect(secondNonce, target.url).not.toBe(firstNonce);
        expect(parseCsp(first.csp).get('script-src'), target.url).toEqual(["'self'"]);
      });

      // 048 task 8.2: the same exact policy and `Reporting-Endpoints` on JSON, asset and 404.
      it(`${target.name}: carries the exact policy with the report directives and Reporting-Endpoints (048 D9)`, async () => {
        const response = await call('GET', target.url);
        expect(response.statusCode, target.url).toBe(target.status);
        expectExactPolicy(response.csp, target.url);
        expect(response.reportingEndpoints, target.url).toBe(EXPECTED_REPORTING_ENDPOINTS);
      });
    }

    it('the Q74 404 of a % target carries the nonce too (Q60: the hooks run before Q74)', async () => {
      const response = await rawGet('/catalog/_user/a%40b.com');
      expect(response.statusCode).toBe(404);
      expect(response.headers.get('content-type') ?? '').not.toMatch(/^text\/html/i);
      const csp = response.headers.get('content-security-policy');
      expect(csp).toBeDefined();
      const nonce = styleNonce(csp ?? '', 'Q74 404');
      expectNonceShape(nonce, 'Q74 404');
      expect(parseCsp(csp ?? '').get('script-src')).toEqual(["'self'"]);
      // 048 task 8.2: the exact policy and `Reporting-Endpoints` reach the Q74 404 too.
      expectExactPolicy(csp ?? '', 'Q74 404');
      expect(response.headers.get('reporting-endpoints')).toBe(EXPECTED_REPORTING_ENDPOINTS);
    });
  });

  describe('HEAD of an app path', () => {
    it('HEAD /catalog/service/payments carries the same policy, with its own nonce', async () => {
      const get = await call('GET', '/catalog/service/payments');
      const head = await call('HEAD', '/catalog/service/payments');
      expect(head.statusCode).toBe(200);
      expect(head.contentType).toMatch(HTML);
      expect(head.body).toBe('');

      const headNonce = styleNonce(head.csp, 'HEAD');
      expectNonceShape(headNonce, 'HEAD');
      expect(headNonce).not.toBe(styleNonce(get.csp, 'GET'));
      expect(cspWithoutNonces(head.csp)).toEqual(cspWithoutNonces(get.csp));
      expect(parseCsp(head.csp).get('script-src')).toEqual(["'self'"]);
      // 048 task 8.2.
      expectExactPolicy(head.csp, 'HEAD');
      expect(head.reportingEndpoints).toBe(EXPECTED_REPORTING_ENDPOINTS);
    });
  });
});
